// Apply translations
for (const loc of locales) {
  const map = ALL[loc];
  if (!map) {
    console.warn(`No translations for ${loc}, skipping`);
    continue;
  }
  const path = join(LANG_DIR, `${loc}.json`);
  const data = JSON.parse(readFileSync(path, 'utf8'));
  let changed = false;
  for (const [dotPath, val] of Object.entries(map)) {
    flatSet(data, dotPath, val);
    changed = true;
  }
  if (changed) {
    writeFileSync(path, JSON.stringify(data, null, 2) + '\n');
    console.log(`${loc}: Applied ${Object.keys(map).length} translations`);
  }
}

